const FK: number[] = [0xa3b1bac6, 0x56aa3350, 0x677d9197, 0xb27022dc];

function buildCK(): number[] {
  const ck: number[] = [];
  for (let i = 0; i < 32; i++) {
    const t0 = ((4 * i + 0) * 7) % 256;
    const t1 = ((4 * i + 1) * 7) % 256;
    const t2 = ((4 * i + 2) * 7) % 256;
    const t3 = ((4 * i + 3) * 7) % 256;
    ck.push(((t0 << 24) | (t1 << 16) | (t2 << 8) | t3) >>> 0);
  }
  return ck;
}

const CK: number[] = buildCK();

function rotl(x: number, n: number): number {
  x = x >>> 0;
  return ((x << n) | (x >>> (32 - n))) >>> 0;
}

function sBoxWord(x: number): number {
  return (
    (SBOX[(x >>> 24) & 0xff] << 24) |
    (SBOX[(x >>> 16) & 0xff] << 16) |
    (SBOX[(x >>> 8) & 0xff] << 8) |
    (SBOX[x & 0xff])
  ) >>> 0;
}

function L(x: number): number {
  return (x ^ rotl(x, 2) ^ rotl(x, 10) ^ rotl(x, 18) ^ rotl(x, 24)) >>> 0;
}

function Lprime(x: number): number {
  return (x ^ rotl(x, 13) ^ rotl(x, 23)) >>> 0;
}

function T(x: number): number {
  return L(sBoxWord(x));
}

function Tprime(x: number): number {
  return Lprime(sBoxWord(x));
}

function readWord(buf: Uint8Array, off: number): number {
  return (
    ((buf[off] << 24) | (buf[off + 1] << 16) | (buf[off + 2] << 8) | buf[off + 3]) >>> 0
  );
}

function writeWord(buf: Uint8Array, off: number, w: number): void {
  buf[off] = (w >>> 24) & 0xff;
  buf[off + 1] = (w >>> 16) & 0xff;
  buf[off + 2] = (w >>> 8) & 0xff;
  buf[off + 3] = w & 0xff;
}

export function sm4KeyExpand(key: Uint8Array): number[] {
  if (key.length !== 16) throw new Error("INVALID_KEY_LENGTH");
  const mk = [readWord(key, 0), readWord(key, 4), readWord(key, 8), readWord(key, 12)];
  const K: number[] = [
    (mk[0] ^ FK[0]) >>> 0,
    (mk[1] ^ FK[1]) >>> 0,
    (mk[2] ^ FK[2]) >>> 0,
    (mk[3] ^ FK[3]) >>> 0,
  ];
  const rk: number[] = [];
  for (let i = 0; i < 32; i++) {
    const tmp = (K[i] ^ Tprime((K[i + 1] ^ K[i + 2] ^ K[i + 3] ^ CK[i]) >>> 0)) >>> 0;
    K.push(tmp);
    rk.push(tmp);
  }
  return rk;
}

// Encrypt a single 16-byte block.
export function sm4EncryptBlock(block: Uint8Array, rk: number[]): Uint8Array {
  const X: number[] = [
    readWord(block, 0),
    readWord(block, 4),
    readWord(block, 8),
    readWord(block, 12),
  ];
  for (let i = 0; i < 32; i++) {
    const tmp = (X[i] ^ T((X[i + 1] ^ X[i + 2] ^ X[i + 3] ^ rk[i]) >>> 0)) >>> 0;
    X.push(tmp);
  }
  const out = new Uint8Array(16);
  writeWord(out, 0, X[35]);
  writeWord(out, 4, X[34]);
  writeWord(out, 8, X[33]);
  writeWord(out, 12, X[32]);
  return out;
}

// Convenience: encrypt one 16-byte block with a raw 16-byte key.
export function sm4Encrypt(plaintext: Uint8Array, key: Uint8Array): Uint8Array {
  const rk = sm4KeyExpand(key);
  return sm4EncryptBlock(plaintext, rk);
}
