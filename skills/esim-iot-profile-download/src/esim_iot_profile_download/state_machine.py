"""eSIM IoT Profile Download 状态机"""

from enum import Enum


class EsimState(str, Enum):
    """eSIM Profile 下载状态机"""

    # 初始状态
    START = "START"

    # 初始化与准备阶段
    WAIT_RESET = "WAIT_RESET"
    WAIT_SELECT_MF = "WAIT_SELECT_MF"
    WAIT_TERMINAL_CAPABILITY = "WAIT_TERMINAL_CAPABILITY"
    WAIT_TERMINAL_PROFILE = "WAIT_TERMINAL_PROFILE"
    WAIT_STATUS = "WAIT_STATUS"
    WAIT_MANAGE_CHANNEL = "WAIT_MANAGE_CHANNEL"
    WAIT_SELECT_ISDR = "WAIT_SELECT_ISDR"

    # 清理阶段（下载前清理）
    WAIT_EUICC_MEMORY_RESET = "WAIT_EUICC_MEMORY_RESET"
    WAIT_FETCH_REFRESH = "WAIT_FETCH_REFRESH"
    WAIT_LIST_NOTIFICATION = "WAIT_LIST_NOTIFICATION"
    WAIT_REMOVE_NOTIFICATION = "WAIT_REMOVE_NOTIFICATION"

    # Profile 安装阶段
    WAIT_GET_EUICC_INFO = "WAIT_GET_EUICC_INFO"
    WAIT_GET_EUICC_CHALLENGE = "WAIT_GET_EUICC_CHALLENGE"
    WAIT_AUTHENTICATE_SERVER = "WAIT_AUTHENTICATE_SERVER"
    WAIT_PREPARE_DOWNLOAD = "WAIT_PREPARE_DOWNLOAD"
    WAIT_LOAD_PROFILE_PACKAGE = "WAIT_LOAD_PROFILE_PACKAGE"

    # 后安装处理
    WAIT_POST_INSTALL_RESET = "WAIT_POST_INSTALL_RESET"
    WAIT_POST_INSTALL_IC1 = "WAIT_POST_INSTALL_IC1"
    WAIT_POST_INSTALL_IC2 = "WAIT_POST_INSTALL_IC2"
    WAIT_POST_INSTALL_SELECT_ISDR = "WAIT_POST_INSTALL_SELECT_ISDR"
    WAIT_GET_PROFILES_INFO = "WAIT_GET_PROFILES_INFO"

    # eIM 启用阶段（间接模式）
    WAIT_ADD_INITIAL_EIM = "WAIT_ADD_INITIAL_EIM"
    WAIT_ENABLE_PSMO = "WAIT_ENABLE_PSMO"
    WAIT_POST_ENABLE_RESET = "WAIT_POST_ENABLE_RESET"
    WAIT_POST_ENABLE_IC = "WAIT_POST_ENABLE_IC"
    WAIT_POST_ENABLE_SELECT_ISDR = "WAIT_POST_ENABLE_SELECT_ISDR"
    WAIT_VERIFY_PROFILE_STATE = "WAIT_VERIFY_PROFILE_STATE"

    # APDU 响应处理状态
    WAIT_GET_RESPONSE = "WAIT_GET_RESPONSE"  # 处理 61XX 响应
    WAIT_FETCH = "WAIT_FETCH"  # 处理 91XX 响应
    WAIT_TERMINAL_RESPONSE = "WAIT_TERMINAL_RESPONSE"  # TERMINAL PROFILE 后的 proactive 应答

    # 终态
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"


# 状态转换表：定义每个状态的下一个状态
STATE_TRANSITIONS = {
    EsimState.START: EsimState.WAIT_RESET,
    EsimState.WAIT_RESET: EsimState.WAIT_SELECT_MF,
    EsimState.WAIT_SELECT_MF: EsimState.WAIT_TERMINAL_CAPABILITY,
    EsimState.WAIT_TERMINAL_CAPABILITY: EsimState.WAIT_TERMINAL_PROFILE,
    EsimState.WAIT_TERMINAL_PROFILE: EsimState.WAIT_STATUS,
    EsimState.WAIT_STATUS: EsimState.WAIT_MANAGE_CHANNEL,
    EsimState.WAIT_MANAGE_CHANNEL: EsimState.WAIT_SELECT_ISDR,
    EsimState.WAIT_SELECT_ISDR: EsimState.WAIT_GET_EUICC_INFO,
    EsimState.WAIT_GET_EUICC_INFO: EsimState.WAIT_GET_EUICC_CHALLENGE,
    EsimState.WAIT_GET_EUICC_CHALLENGE: EsimState.WAIT_AUTHENTICATE_SERVER,
    EsimState.WAIT_AUTHENTICATE_SERVER: EsimState.WAIT_PREPARE_DOWNLOAD,
    EsimState.WAIT_PREPARE_DOWNLOAD: EsimState.WAIT_LOAD_PROFILE_PACKAGE,
    EsimState.WAIT_LOAD_PROFILE_PACKAGE: EsimState.WAIT_POST_INSTALL_RESET,
    EsimState.WAIT_POST_INSTALL_RESET: EsimState.WAIT_POST_INSTALL_IC1,
    EsimState.WAIT_POST_INSTALL_IC1: EsimState.WAIT_POST_INSTALL_IC2,
    EsimState.WAIT_POST_INSTALL_IC2: EsimState.WAIT_POST_INSTALL_SELECT_ISDR,
    EsimState.WAIT_POST_INSTALL_SELECT_ISDR: EsimState.WAIT_GET_PROFILES_INFO,
    EsimState.WAIT_GET_PROFILES_INFO: EsimState.SUCCESS,
}

# 间接模式的额外状态转换
INDIRECT_MODE_TRANSITIONS = {
    EsimState.WAIT_GET_PROFILES_INFO: EsimState.WAIT_ADD_INITIAL_EIM,
    EsimState.WAIT_ADD_INITIAL_EIM: EsimState.WAIT_ENABLE_PSMO,
    EsimState.WAIT_ENABLE_PSMO: EsimState.WAIT_POST_ENABLE_RESET,
    EsimState.WAIT_POST_ENABLE_RESET: EsimState.WAIT_POST_ENABLE_SELECT_ISDR,
    EsimState.WAIT_POST_ENABLE_SELECT_ISDR: EsimState.WAIT_VERIFY_PROFILE_STATE,
    EsimState.WAIT_VERIFY_PROFILE_STATE: EsimState.SUCCESS,
}
